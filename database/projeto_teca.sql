CREATE DATABASE IF NOT EXISTS projeto_teca CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE projeto_teca;

CREATE TABLE funcionario (
    id INT AUTO_INCREMENT PRIMARY KEY,
    nome VARCHAR(200) NOT NULL,
    cpf VARCHAR(14) NOT NULL UNIQUE,
    telefone VARCHAR(20),
    senha VARCHAR(255) NOT NULL,
    email VARCHAR(200),
    data_inclusao DATETIME,
    data_alteracao DATETIME,
    inclusao_funcionario_id INT,
    alteracao_funcionario_id INT
);

CREATE TABLE autor (
    id INT AUTO_INCREMENT PRIMARY KEY,
    nome VARCHAR(200) NOT NULL,
    data_inclusao DATETIME,
    data_alteracao DATETIME,
    inclusao_funcionario_id INT,
    alteracao_funcionario_id INT
);

CREATE TABLE livro (
    id INT AUTO_INCREMENT PRIMARY KEY,
    titulo VARCHAR(200) NOT NULL,
    ano INT,
    genero VARCHAR(100),
    isbn VARCHAR(13),
    sinopse TEXT,
    cor VARCHAR(7),
    autor_id INT NOT NULL,
    data_inclusao DATETIME,
    data_alteracao DATETIME,
    inclusao_funcionario_id INT,
    alteracao_funcionario_id INT,
    FOREIGN KEY (autor_id) REFERENCES autor (id)
);

CREATE TABLE cliente (
    id INT AUTO_INCREMENT PRIMARY KEY,
    nome VARCHAR(200) NOT NULL,
    telefone VARCHAR(20),
    email VARCHAR(200),
    cpf VARCHAR(14),
    rg VARCHAR(20),
    codigo_acesso VARCHAR(8) UNIQUE,
    data_nascimento DATE,
    data_inclusao DATETIME,
    data_alteracao DATETIME,
    inclusao_funcionario_id INT,
    alteracao_funcionario_id INT
);

CREATE TABLE emprestimo (
    id INT AUTO_INCREMENT PRIMARY KEY,
    livro_id INT NOT NULL,
    cliente_id INT NOT NULL,
    data_vencimento DATE NOT NULL,
    data_inclusao DATETIME,
    data_alteracao DATETIME,
    data_renovacao DATE,
    data_devolucao DATETIME,
    inclusao_funcionario_id INT,
    alteracao_funcionario_id INT,
    renovacao_funcionario_id INT,
    devolucao_funcionario_id INT,
    FOREIGN KEY (livro_id) REFERENCES livro (id),
    FOREIGN KEY (cliente_id) REFERENCES cliente (id)
);

